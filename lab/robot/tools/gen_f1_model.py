"""Write src/CR_F1Model.mqh, the frozen F1 scorecard (SPEC 3, F1B and F1E), from the lab's model file.

    python3 -I lab/robot/tools/gen_f1_model.py [--model PATH] [--out PATH] [--check]

Source: lab/r2/tracks/ml/models/B1_ridge_full.json, key "frozen" (ml/strategy.py:295-297 names it; score_model
:208-212 and _design :195-205 use it). Owner: step E.

The generator REFUSES (exit 2, nothing written) when:
  * the model file's sha256 is not d191cbbcc2fc4d2cae31182f14f412069a194b69c2a9d9ae6bca0d0f5dee644e (SPEC 3);
  * the frozen model is not the linear scorecard CR_Rule_F1.mqh computes: type "linear", numeric inputs taken from
    the 15 features of ml/strategy.py FEATURES (:72-73), dummies on "hour" or "dow" only, one mean, one std > 0 and
    one coefficient per input, a finite clip > 0, and the threshold of q "0.5" (FINALISTS, :297).
Doubles are written with %.17g, which gives the same double back when the file is read.
--check: build the text in memory and compare it with --out (exit 1 when they differ, nothing written).
"""
import argparse
import hashlib
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROBOT = os.path.dirname(HERE)
LAB = os.path.dirname(ROBOT)
MODEL = os.path.join(LAB, "r2", "tracks", "ml", "models", "B1_ridge_full.json")
OUT = os.path.join(ROBOT, "src", "CR_F1Model.mqh")
SHA256 = "d191cbbcc2fc4d2cae31182f14f412069a194b69c2a9d9ae6bca0d0f5dee644e"
Q = "0.5"                                   # FINALISTS["F1_brk_ridge_filter"]["params"]["q"] (ml/strategy.py:297)
# ml/strategy.py:72-73: the order in which CR_Rule_F1.mqh computes the features (index = position in this list)
FEATURES = ["brk", "bar", "body", "ret4", "ret14", "ret70", "chan", "vol", "pos", "seq", "opp", "pdd", "dret", "hour", "dow"]
DUMMY_OK = ("hour", "dow")


class Refused(Exception):
    pass


def g17(x):
    """a C / MQL5 double literal that reads back as the same double (17 significant digits)"""
    x = float(x)
    if not math.isfinite(x):
        raise Refused(f"value {x!r} is not a finite number")
    s = "%.17g" % x
    if not any(ch in s for ch in ".e"):
        s += ".0"
    assert float(s) == x
    return s


def load(path):
    raw = open(path, "rb").read()
    sha = hashlib.sha256(raw).hexdigest()
    if sha != SHA256:
        raise Refused(f"{path}: sha256 {sha} is not the frozen model's {SHA256}")
    return json.loads(raw.decode("utf-8"))["frozen"], sha


def check_model(m):
    if m.get("type") != "linear":
        raise Refused(f"model type {m.get('type')!r}: only the linear scorecard is ported")
    num, mean, std, coef = m["num"], m["mean"], m["std"], m["coef"]
    dums = m.get("dummies", [])
    unknown = [f for f in num if f not in FEATURES]
    if unknown:
        raise Refused(f"numeric inputs {unknown} are not features of ml/strategy.py")
    if len(set(num)) != len(num):
        raise Refused("a numeric input is listed twice")
    if not (len(mean) == len(std) == len(num)):
        raise Refused("mean and std must have one value per numeric input")
    if any(not (float(s) > 0.0) for s in std):
        raise Refused("every std must be > 0")
    if len(coef) != len(num) + len(dums):
        raise Refused(f"{len(coef)} coefficients for {len(num)} inputs and {len(dums)} dummies")
    for d in dums:
        if len(d) != 3 or d[0] not in DUMMY_OK:
            raise Refused(f"dummy {d!r}: only [hour|dow, lo, hi] is ported")
    clip = float(m.get("clip", 4.0))                       # _design :201 (default 4.0)
    if not (math.isfinite(clip) and clip > 0.0):
        raise Refused(f"clip {clip!r}")
    thr = m["thr"]
    if not isinstance(thr, dict) or Q not in thr:
        raise Refused(f"no threshold for q {Q!r}")
    return num, mean, std, coef, dums, clip, float(thr[Q])


def row(vals, fmt):
    return "{" + ", ".join(fmt(v) for v in vals) + "}"


def text(m, sha):
    num, mean, std, coef, dums, clip, thr = check_model(m)
    nn, nd = len(num), len(dums)
    lines = [
        "//+------------------------------------------------------------------+",
        "//| CR_F1Model.mqh - GENERATED by tools/gen_f1_model.py (step E) from |",
        "//| lab/r2/tracks/ml/models/B1_ridge_full.json[\"frozen\"], refused     |",
        "//| unless its sha256 is d191cbbcc2fc4d2cae31182f14f412069a194b69c2a9 |",
        "//| d9ae6bca0d0f5dee644e. Constants written with %.17g.               |",
        "//| Do not edit by hand: run the generator again.                    |",
        "//|                                                                  |",
        "//| The F1 score (ml/strategy.py score_model :208-212, _design       |",
        "//| :195-205), computed by CR_Rule_F1.mqh:                           |",
        "//|   z_k = (x[NUM_FEAT[k]] - MEAN[k]) / STD[k], clipped to +/- CLIP |",
        "//|   d_j = 1 when DUM_LO[j] <= x[DUM_FEAT[j]] <= DUM_HI[j], else 0  |",
        "//|   score = INTERCEPT + (sum of z_k COEF[k], then d_j COEF[NNUM+j])|",
        "//|   taken when score >= THR (thr[\"0.5\"], FINALISTS q 0.5)          |",
        "//| x = the 15 features in ml/strategy.py FEATURES order (:72-73):   |",
        "//|   0 brk 1 bar 2 body 3 ret4 4 ret14 5 ret70 6 chan 7 vol 8 pos   |",
        "//|   9 seq 10 opp 11 pdd 12 dret 13 hour 14 dow                     |",
        "//+------------------------------------------------------------------+",
        "#ifndef CR_F1MODEL_MQH",
        "#define CR_F1MODEL_MQH",
        "#define CR_F1_READY 1",
        f'#define CR_F1_SHA256 "{sha}"',
        f"#define CR_F1_NFEAT {len(FEATURES)}",
        f"#define CR_F1_NNUM {nn}",
        f"#define CR_F1_NDUM {nd}",
        f"#define CR_F1_NCOEF {nn + nd}",
        f"#define CR_F1_CLIP {g17(clip)}",
        f"#define CR_F1_INTERCEPT {g17(m['intercept'])}",
        f"#define CR_F1_THR {g17(thr)}",
        "// numeric inputs, in the model's order: " + " ".join(num),
        f"int    CR_F1_NUM_FEAT[CR_F1_NNUM] = {row([FEATURES.index(f) for f in num], str)};",
        f"double CR_F1_MEAN[CR_F1_NNUM] = {row(mean, g17)};",
        f"double CR_F1_STD[CR_F1_NNUM] = {row(std, g17)};",
        "// dummies, in the model's order: " + " ".join(f"{d[0]}[{d[1]},{d[2]}]" for d in dums),
        f"int    CR_F1_DUM_FEAT[CR_F1_NDUM] = {row([FEATURES.index(d[0]) for d in dums], str)};",
        f"double CR_F1_DUM_LO[CR_F1_NDUM] = {row([d[1] for d in dums], g17)};",
        f"double CR_F1_DUM_HI[CR_F1_NDUM] = {row([d[2] for d in dums], g17)};",
        "// coefficients: the numeric inputs, then the dummies",
        f"double CR_F1_COEF[CR_F1_NCOEF] = {row(coef, g17)};",
        "#endif",
    ]
    out = "\n".join(lines) + "\n"
    out.encode("ascii")
    return out


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default=MODEL)
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    try:
        m, sha = load(a.model)
        t = text(m, sha)
    except (Refused, KeyError, ValueError) as e:
        sys.stderr.write(f"gen_f1_model: REFUSED: {e}\n")
        return 2
    if a.check:
        same = os.path.exists(a.out) and open(a.out, encoding="ascii").read() == t
        print(f"gen_f1_model: {a.out} {'equals' if same else 'DIFFERS FROM'} the generator's output (model sha256 {sha})")
        return 0 if same else 1
    with open(a.out, "w", encoding="ascii", newline="\n") as f:
        f.write(t)
    print(f"gen_f1_model: {a.out} written from {a.model} (sha256 {sha}, {len(m['num'])} inputs, "
          f"{len(m.get('dummies', []))} dummies, threshold {g17(m['thr'][Q])})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
