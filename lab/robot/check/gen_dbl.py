"""Generate check/dbl/CR_Clock_dbl.mqh: a table-driven copy of the CR_Clock API for the wave-1 tests (SPEC 8).

    python3 -I lab/robot/check/gen_dbl.py

Steps B and I compile it in place of src/CR_Clock.mqh (check/build.py --subst CR_Clock.mqh=check/dbl/CR_Clock_dbl.mqh),
so they never depend on step A's file running beside them. Same include guard and same function signatures as
src/CR_Clock.mqh (check/test_s0_dbl.py checks both). Tables, from the lab's own references:
  * US and UK summer time: the UTC instants where zoneinfo's America/New_York and Europe/London offsets change,
    2000-2040;
  * NYSE full closures and 13:00 half days: idxus_lib.us_holidays (the lab's calendar), 2000-2040;
  * the gold holiday closures of SPEC 2.1 built on them: the NYSE's observed Good Friday, Christmas and New Year
    [day before 17:00, day 18:00); the other NYSE full holidays (the special closures excepted) [13:00, 18:00); the
    Friday after Thanksgiving and a Christmas Eve half day [13:45, 18:00) (New York clock).
The rest is computed: daily and weekly closures per family, typed InpExtraClosures, AddTradingDays and BusinessDays
(pandas BDay, no holidays), RealExitMinute.
"""
import datetime as dt
import os
import sys
from zoneinfo import ZoneInfo

HERE = os.path.dirname(os.path.abspath(__file__))
LAB = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(LAB, "r2", "tracks", "idx_us"))
import idxus_lib as cm  # noqa: E402

Y0, Y1 = 2000, 2040
UTC = dt.timezone.utc


def transitions(tz):
    """[(on, off)] per year: UTC seconds where the zone enters and leaves summer time"""
    z = ZoneInfo(tz)
    out = []
    for y in range(Y0, Y1 + 1):
        t = dt.datetime(y, 1, 1, tzinfo=UTC)
        end = dt.datetime(y + 1, 1, 1, tzinfo=UTC)
        prev = t.astimezone(z).utcoffset()
        on = off = None
        while t < end:
            t2 = t + dt.timedelta(hours=1)
            o = t2.astimezone(z).utcoffset()
            if o != prev:
                # the change happens on a whole hour (UTC) in both zones
                if o > prev:
                    on = int(t2.timestamp())
                else:
                    off = int(t2.timestamp())
                prev = o
            t = t2
        assert on and off, (tz, y)
        out.append((on, off))
    return out


def day_secs(d):
    return int(dt.datetime(d.year, d.month, d.day, tzinfo=UTC).timestamp())


def calendars():
    full, half, long_, short_, h1345 = [], [], [], [], []
    for y in range(Y0, Y1 + 1):
        f, h = cm.us_holidays(y)
        full += sorted(f)
        half += sorted(h)
        gf = cm._easter(y) - dt.timedelta(days=2)
        xmas = cm._observed(dt.date(y, 12, 25))
        ny = dt.date(y, 1, 1)
        nyo = dt.date(y, 1, 2) if ny.weekday() == 6 else (ny if ny.weekday() < 5 else None)
        lg = {d for d in (gf, xmas, nyo) if d is not None and d in f}
        long_ += sorted(lg)
        short_ += sorted(f - lg - cm.SPECIAL_CLOSURES)
        tg = cm._nth(y, 11, 3, 4)
        h1345 += sorted(d for d in h if d == tg + dt.timedelta(days=1) or (d.month == 12 and d.day == 24))
    return [sorted(set(x)) for x in (full, half, long_, short_, h1345)]


def arr(name, vals, per_line=6):
    body = ",\n   ".join(", ".join(str(v) for v in vals[i:i + per_line]) for i in range(0, len(vals), per_line))
    return f"long {name}[] = {{\n   {body}}};\n"


TEMPLATE = r'''//+------------------------------------------------------------------+
//| CR_Clock_dbl.mqh - GENERATED by check/gen_dbl.py (S0). Do not edit.|
//| Table-driven copy of the CR_Clock API (src/CR_Clock.mqh) for the |
//| wave-1 tests (steps B and I, SPEC 8). Same guard, same signatures.|
//| Tables: zoneinfo summer time {Y0}-{Y1}; NYSE idxus_lib.us_holidays. |
//+------------------------------------------------------------------+
#ifndef CR_CLOCK_MQH
#define CR_CLOCK_MQH
#include "../../src/CR_Types.mqh"

#define CR_DBL_Y0 {Y0}
#define CR_DBL_Y1 {Y1}
#define CR_DBL_MAXT 64                 // typed closures kept
// summer time: g_dbl_us[2k] = start, g_dbl_us[2k + 1] = end, UTC seconds, year CR_DBL_Y0 + k
{US}{UK}// NYSE dates (00:00 of the New York date, as UTC seconds of that calendar date)
{FULL}{HALF}// gold holiday closures (SPEC 2.1): long = [day before 17:00, day 18:00); short = [13:00, 18:00); h1345 = [13:45, 18:00)
{LONG}{SHORT}{H1345}
int      g_dbl_nt = 0;                 // typed closures: kind 0 NYSE, 1 HALF, 2 window (family, c0, c1 in New York wall clock)
int      g_dbl_tk[CR_DBL_MAXT];
int      g_dbl_tf[CR_DBL_MAXT];
datetime g_dbl_t0[CR_DBL_MAXT];
datetime g_dbl_t1[CR_DBL_MAXT];

bool ClkDblFind(const long &a[], const long v)
  {
   int lo = 0, hi = ArraySize(a) - 1;
   while(lo <= hi)
     {
      int mid = (lo + hi) / 2;
      if(a[mid] == v) return true;
      if(a[mid] < v) lo = mid + 1;
      else hi = mid - 1;
     }
   return false;
  }

int ClkYear(const datetime t)
  {
   MqlDateTime x;
   TimeToStruct(t, x);
   return x.year;
  }

bool ClkDblIn(const long &a[], const datetime utc)
  {
   int k = ClkYear(utc) - CR_DBL_Y0;
   if(k < 0 || 2 * k + 1 >= ArraySize(a)) return false;
   return utc >= a[2 * k] && utc < a[2 * k + 1];
  }

bool     ClkUsDst(const datetime utc) { return ClkDblIn(g_dbl_us, utc); }
bool     ClkUkDst(const datetime utc) { return ClkDblIn(g_dbl_uk, utc); }
datetime ClkServerToUtc(const datetime srv) { datetime u3 = srv - 3 * 3600; return ClkUsDst(u3) ? u3 : u3 + 3600; }
datetime ClkUtcToServer(const datetime utc) { return utc + (ClkUsDst(utc) ? 3 * 3600 : 2 * 3600); }
datetime ClkUtcToNy(const datetime utc) { return ClkUtcToServer(utc) - 7 * 3600; }
datetime ClkNyToUtc(const datetime ny) { return ClkServerToUtc(ny + 7 * 3600); }
datetime ClkUtcToLdn(const datetime utc) { return utc + (ClkUkDst(utc) ? 3600 : 0); }
datetime ClkLdnToUtc(const datetime ldn) { datetime u = ldn - 3600; return ClkUkDst(u) ? u : ldn; }
datetime ClkDay(const datetime t) { return t - t % 86400; }
int      ClkMinOfDay(const datetime t) { return (int)((t % 86400) / 60); }

int ClkDow(const datetime t)
  {
   MqlDateTime x;
   TimeToStruct(t, x);
   return x.day_of_week;
  }

datetime ClkServerDay(const datetime utc) { return ClkDay(ClkUtcToServer(utc)); }

datetime ClkServerWeek(const datetime utc)
  {
   datetime d = ClkServerDay(utc);
   return d - ((ClkDow(d) + 6) % 7) * 86400;
  }

// pandas BDay(n), n >= 0, on a date at 00:00: a weekend date rolls to Monday, which counts as the first day
datetime ClkDblBDay(const datetime day, const int n)
  {
   datetime d = day;
   int k = n;
   int dow = ClkDow(d);
   if(dow == 6 || dow == 0)
     {
      d += (dow == 6 ? 2 : 1) * 86400;
      if(k > 0) k--;
     }
   while(k > 0)
     {
      d += 86400;
      dow = ClkDow(d);
      if(dow != 0 && dow != 6) k--;
     }
   return d;
  }

// trend/strategy.py:107-111: n business days after the server date (New York + 7 h), the same New York wall time
datetime ClkAddTradingDays(const datetime utc, const int n)
  {
   datetime srv = ClkUtcToNy(utc) + 7 * 3600;
   datetime d = ClkDay(srv);
   return ClkNyToUtc(ClkDblBDay(d, n) + (srv - d) - 7 * 3600);
  }

datetime ClkBusinessDays(const datetime date, const int n)
  {
   datetime d = ClkDay(date);
   return ClkDblBDay(d, n) + (date - d);
  }

int ClkNyse(const datetime ny_date)
  {
   datetime d = ClkDay(ny_date);
   for(int i = 0; i < g_dbl_nt; i++)
      if(g_dbl_tk[i] < 2 && g_dbl_t0[i] == d) return g_dbl_tk[i] == 0 ? CR_NYSE_FULL : CR_NYSE_HALF;
   if(ClkDblFind(g_dbl_full, d)) return CR_NYSE_FULL;
   if(ClkDblFind(g_dbl_half, d)) return CR_NYSE_HALF;
   return CR_NYSE_OPEN;
  }

// "yyyy.mm.dd" -> 00:00 of that date; "yyyy.mm.dd hh:mm" -> that minute; false when it does not parse
bool ClkDblParseTime(const string s, const bool with_time, datetime &t)
  {
   string x = s;
   StringTrimLeft(x);
   StringTrimRight(x);
   if(StringLen(x) != (with_time ? 16 : 10)) return false;
   if(StringSubstr(x, 4, 1) != "." || StringSubstr(x, 7, 1) != ".") return false;
   MqlDateTime d;
   ZeroMemory(d);
   d.year = (int)StringToInteger(StringSubstr(x, 0, 4));
   d.mon = (int)StringToInteger(StringSubstr(x, 5, 2));
   d.day = (int)StringToInteger(StringSubstr(x, 8, 2));
   if(with_time)
     {
      if(StringSubstr(x, 10, 1) != " " || StringSubstr(x, 13, 1) != ":") return false;
      d.hour = (int)StringToInteger(StringSubstr(x, 11, 2));
      d.min = (int)StringToInteger(StringSubstr(x, 14, 2));
     }
   if(d.year < 2000 || d.year > 2100 || d.mon < 1 || d.mon > 12 || d.day < 1 || d.day > 31 || d.hour > 23 || d.min > 59) return false;
   t = StructToTime(d);
   MqlDateTime back;
   TimeToStruct(t, back);
   return back.day == d.day;
  }

// InpExtraClosures (SPEC 2.1): "NYSE yyyy.mm.dd", "HALF yyyy.mm.dd", "XAU|IDX|CRY yyyy.mm.dd hh:mm-yyyy.mm.dd hh:mm"
bool ClkInit(const string extra, string &err)
  {
   err = "";
   g_dbl_nt = 0;
   string e = extra;
   StringTrimLeft(e);
   StringTrimRight(e);
   if(e == "") return true;
   string part[];
   int n = StringSplit(e, ';', part);
   for(int i = 0; i < n; i++)
     {
      string p = part[i];
      StringTrimLeft(p);
      StringTrimRight(p);
      if(p == "") continue;
      if(g_dbl_nt >= CR_DBL_MAXT) { err = "InpExtraClosures: too many entries"; return false; }
      string kind = StringSubstr(p, 0, 4);
      string rest = StringSubstr(p, 4);
      datetime t0 = 0, t1 = 0;
      int k = -1, fam = -1;
      if(kind == "NYSE" || kind == "HALF")
        {
         if(!ClkDblParseTime(rest, false, t0)) { err = "InpExtraClosures: bad date in '" + p + "'"; return false; }
         k = (kind == "NYSE") ? 0 : 1;
        }
      else
        {
         string f3 = StringSubstr(p, 0, 3);
         fam = (f3 == "XAU") ? CR_FAM_XAU : ((f3 == "IDX") ? CR_FAM_IDX : ((f3 == "CRY") ? CR_FAM_CRY : -1));
         string w = StringSubstr(p, 3);
         StringTrimLeft(w);
         int dash = StringFind(w, "-");
         if(fam < 0 || dash != 16 || !ClkDblParseTime(StringSubstr(w, 0, 16), true, t0) || !ClkDblParseTime(StringSubstr(w, 17), true, t1)
            || t1 <= t0)
           {
            err = "InpExtraClosures: bad entry '" + p + "'";
            return false;
           }
         k = 2;
        }
      g_dbl_tk[g_dbl_nt] = k;
      g_dbl_tf[g_dbl_nt] = fam;
      g_dbl_t0[g_dbl_nt] = t0;
      g_dbl_t1[g_dbl_nt] = t1;
      g_dbl_nt++;
     }
   return true;
  }

// closures of a family around New York date nyd (New York wall clock, [a, b)); appended to a, b
void ClkDblAdd(datetime &a[], datetime &b[], int &n, const datetime x0, const datetime x1)
  {
   if(x1 <= x0) return;
   ArrayResize(a, n + 1, 64);
   ArrayResize(b, n + 1, 64);
   a[n] = x0;
   b[n] = x1;
   n++;
  }

void ClkDblDay(const int family, const datetime nyd, datetime &a[], datetime &b[], int &n)
  {
   int dow = ClkDow(nyd);
   datetime h = 3600, m = 60;
   if(family == CR_FAM_XAU)
     {
      if(dow >= 1 && dow <= 4) ClkDblAdd(a, b, n, nyd + 17 * h, nyd + 18 * h);
      if(dow == 5) ClkDblAdd(a, b, n, nyd + 17 * h, nyd + 2 * 86400 + 18 * h);
      if(ClkDblFind(g_dbl_long, nyd)) ClkDblAdd(a, b, n, nyd - 86400 + 17 * h, nyd + 18 * h);
      if(ClkDblFind(g_dbl_short, nyd)) ClkDblAdd(a, b, n, nyd + 13 * h, nyd + 18 * h);
      if(ClkDblFind(g_dbl_h1345, nyd)) ClkDblAdd(a, b, n, nyd + 13 * h + 45 * m, nyd + 18 * h);
     }
   else if(family == CR_FAM_IDX)
     {
      if(dow >= 1 && dow <= 4) ClkDblAdd(a, b, n, nyd + 16 * h + 15 * m, nyd + 18 * h);
      if(dow == 5) ClkDblAdd(a, b, n, nyd + 16 * h + 15 * m, nyd + 2 * 86400 + 18 * h);
     }
   else if(family == CR_FAM_CRY)
     {
      if(dow == 5) ClkDblAdd(a, b, n, nyd + 16 * h + 55 * m, nyd + 2 * 86400 + 17 * h);
     }
  }

bool ClkInClosure(const int family, const datetime utc, datetime &c0, datetime &c1)
  {
   c0 = 0;
   c1 = 0;
   datetime ny = ClkUtcToNy(utc);
   datetime d = ClkDay(ny);
   datetime a[], b[];
   int n = 0;
   for(int k = -4; k <= 4; k++) ClkDblDay(family, d + k * 86400, a, b, n);
   for(int i = 0; i < g_dbl_nt; i++)
      if(g_dbl_tk[i] == 2 && g_dbl_tf[i] == family) ClkDblAdd(a, b, n, g_dbl_t0[i], g_dbl_t1[i]);
   // the merged interval that holds ny
   datetime lo = 0, hi = 0;
   bool found = false;
   for(int i = 0; i < n; i++)
      if(a[i] <= ny && ny < b[i]) { lo = a[i]; hi = b[i]; found = true; break; }
   if(!found) return false;
   bool grew = true;
   while(grew)
     {
      grew = false;
      for(int i = 0; i < n; i++)
         if(a[i] <= hi && b[i] >= lo && (a[i] < lo || b[i] > hi))
           {
            if(a[i] < lo) lo = a[i];
            if(b[i] > hi) hi = b[i];
            grew = true;
           }
     }
   c0 = ClkNyToUtc(lo);
   c1 = ClkNyToUtc(hi);
   return true;
  }

// SPEC 2.1 (follower only): a gap-rule exit inside a known closure moves to its last minute before it
datetime ClkRealExitMinute(const datetime x, const int family, const bool gap_rule, const datetime fri_end_utc)
  {
   datetime c0 = 0, c1 = 0;
   if(gap_rule && ClkInClosure(family, x, c0, c1) && x < c1 - 30 * 60) return c0 - 60;
   if(family == CR_FAM_CRY && fri_end_utc > 0 && x >= fri_end_utc - 60 && x < fri_end_utc + 3 * 86400) return fri_end_utc - 60;
   return x;
  }

long   ClkRuleOffset(const datetime utc) { return ClkUsDst(utc) ? 3 * 3600 : 2 * 3600; }
string ClkStr(const datetime t) { return TimeToString(t, TIME_DATE | TIME_MINUTES); }
#endif
'''


def main():
    us, uk = transitions("America/New_York"), transitions("Europe/London")
    full, half, long_, short_, h1345 = calendars()
    flat = lambda pairs: [v for p in pairs for v in p]
    rep = {"Y0": str(Y0), "Y1": str(Y1), "US": arr("g_dbl_us", flat(us)), "UK": arr("g_dbl_uk", flat(uk)),
           "FULL": arr("g_dbl_full", [day_secs(d) for d in full]), "HALF": arr("g_dbl_half", [day_secs(d) for d in half]),
           "LONG": arr("g_dbl_long", [day_secs(d) for d in long_]), "SHORT": arr("g_dbl_short", [day_secs(d) for d in short_]),
           "H1345": arr("g_dbl_h1345", [day_secs(d) for d in h1345])}
    text = TEMPLATE
    for k, v in rep.items():
        text = text.replace("{" + k + "}", v)
    os.makedirs(os.path.join(HERE, "dbl"), exist_ok=True)
    p = os.path.join(HERE, "dbl", "CR_Clock_dbl.mqh")
    with open(p, "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    print(f"gen_dbl: {p}: US/UK summer time {Y0}-{Y1}, NYSE {len(full)} full + {len(half)} half days, gold long {len(long_)} "
          f"short {len(short_)} 13:45 {len(h1345)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
