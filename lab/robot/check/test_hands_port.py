"""T9 hands port: the hands' tests that SPEC 7 T9 keeps, run on CR_Broker, CR_Guards, CR_Ledger and CR_Sizing (step J).

    python3 -I lab/robot/check/test_hands_port.py

check/test_exec.cpp holds the worlds. This script builds it twice (plain and sanitizer, 0 warnings each) from a tree
under lab/robot/build/hands_tree that holds the seven module files and an entry including CR_Sizing.mqh and
CR_Guards.mqh (so the sizing ports O7-O11 run too, -DCR_EXEC_SIZING), runs "test_exec hands" and checks:
  - every id that T9 names and the hands' file (lab/live_ai/check/test_mains.py) defines has one HANDS line, PASS, in
    both builds (an id T9 names that the hands' file does not define, X5, is reported, not required);
  - the two builds print the same HANDS lines and every other check of test_exec holds.
Writes check/out/test_hands_port/summary.json and hands.csv (id, state, the hands' title, what the port checks).
Exit 0 when all of that holds.
"""
import csv
import json
import os
import re
import shutil
import subprocess
import sys
import time

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
ROBOT = os.path.dirname(HERE)
LAB = os.path.dirname(ROBOT)
BUILD = os.path.join(ROBOT, "build")
OUT = os.path.join(HERE, "out", "test_hands_port")
HANDS = os.path.join(LAB, "live_ai", "check", "test_mains.py")
sys.path.insert(0, HERE)
from build import build  # noqa: E402

MODULES = ["CR_Types.mqh", "CR_Clock.mqh", "CR_Journal.mqh", "CR_Ledger.mqh", "CR_Sizing.mqh", "CR_Broker.mqh", "CR_Guards.mqh"]
# SPEC 7, T9
T9 = "O1-O5, O7-O13, O16-O19, O21-O26, M1-M4, C1, C3-C5, N1-N3, T1-T3, X9-X12, R12, R19, D7, F1-F4, K7-K19, X4-X8"


def expand(spec):
    ids = []
    for part in spec.split(","):
        part = part.strip()
        m = re.fullmatch(r"([A-Z])(\d+)-\1?(\d+)", part)
        if m:
            ids += [f"{m.group(1)}{k}" for k in range(int(m.group(2)), int(m.group(3)) + 1)]
        else:
            ids.append(part)
    return ids


def hands_titles():
    """id -> title of every test the hands' file defines"""
    out = {}
    with open(HANDS) as f:
        text = f.read()
    for m in re.finditer(r'@test\("([A-Z]+\d+)",\s*"((?:[^"\\]|\\.)*)"(?:\s*\n?\s*"((?:[^"\\]|\\.)*)")?', text):
        out[m.group(1)] = (m.group(2) + (m.group(3) or "")).strip()
    return out


def make_tree():
    dst = os.path.join(BUILD, "hands_tree")
    if os.path.isdir(dst):
        shutil.rmtree(dst)
    os.makedirs(dst)
    for f in MODULES:
        shutil.copy(os.path.join(ROBOT, "src", f), os.path.join(dst, f))
    entry = os.path.join(dst, "CR_ExecHands.mqh")
    with open(entry, "w") as h:
        h.write("// T9 entry (generated by check/test_hands_port.py): the broker, guards, ledger and sizing modules\n"
                "#ifndef CR_EXEC_HANDS_MQH\n#define CR_EXEC_HANDS_MQH\n"
                "#include \"CR_Sizing.mqh\"\n#include \"CR_Guards.mqh\"\n#endif\n")
    return entry


def run(exe, tag):
    d = os.path.join(OUT, tag)
    if os.path.isdir(d):
        shutil.rmtree(d)
    os.makedirs(d)
    t0 = time.time()
    r = subprocess.run([exe, "hands", d], capture_output=True, text=True, timeout=900, cwd=ROBOT)
    lines = r.stdout.splitlines()
    hands = {}
    order = []
    for ln in lines:
        m = re.match(r"^HANDS (\S+) (PASS|FAIL|PART) (.*)$", ln)
        if m:
            if m.group(1) not in hands:
                order.append(m.group(1))
            hands.setdefault(m.group(1), []).append((m.group(2), m.group(3)))
    tail = [ln for ln in lines if ln.startswith("test_exec:") or ln.startswith("  failed in")]
    return {"exit": r.returncode, "hands": hands, "order": order, "tail": tail, "stderr": r.stderr[-4000:],
            "sec": round(time.time() - t0, 1), "lines": [ln for ln in lines if ln.startswith("HANDS ")]}


def main():
    os.makedirs(OUT, exist_ok=True)
    t0 = time.time()
    titles = hands_titles()
    want = expand(T9)
    absent = [i for i in want if i not in titles]
    need = [i for i in want if i in titles]
    entry = make_tree()
    main_cpp = os.path.join(HERE, "test_exec.cpp")
    builds, warns = {}, {}
    for tag, san in (("plain", False), ("san", True)):
        exe, warn = build(entry, name="test_hands_port" + ("_san" if san else ""), main=main_cpp, defines=["CR_EXEC_SIZING"], sanitize=san)
        builds[tag] = exe
        warns[tag] = warn
    res = {tag: run(exe, tag) for tag, exe in builds.items()}
    problems = []
    for tag in builds:
        if warns[tag]:
            problems.append(f"{tag} build: {len(warns[tag])} warnings: {warns[tag][:3]}")
        r = res[tag]
        if r["exit"] != 0:
            problems.append(f"{tag} run: exit {r['exit']}: {' | '.join(r['tail'])} {r['stderr'][-600:]}")
        for i in need:
            got = r["hands"].get(i)
            if not got:
                problems.append(f"{tag}: {i} has no HANDS line")
            elif len(got) != 1:
                problems.append(f"{tag}: {i} has {len(got)} HANDS lines")
            elif got[0][0] != "PASS":
                problems.append(f"{tag}: {i} {got[0][0]}: {got[0][1]}")
        extra = [i for i in r["order"] if i not in need]
        if extra:
            problems.append(f"{tag}: HANDS lines for ids T9 does not name: {extra}")
    if res["plain"]["lines"] != res["san"]["lines"]:
        problems.append("the plain and sanitizer builds print different HANDS lines")
    rows = []
    for i in need:
        got = res["plain"]["hands"].get(i, [("MISSING", "")])[0]
        rows.append({"id": i, "state": got[0], "hands_title": titles.get(i, ""), "port_checks": got[1]})
    with open(os.path.join(OUT, "hands.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["id", "state", "hands_title", "port_checks"])
        w.writeheader()
        w.writerows(rows)
    retired = sorted((i for i in titles if i not in want), key=lambda x: (x[0], int(re.sub(r"\D", "", x) or 0)))
    summary = {"named_by_T9": len(want), "defined_by_hands": len(need), "absent_from_hands": absent,
               "pass_plain": sum(1 for i in need if res["plain"]["hands"].get(i, [("", "")])[0][0] == "PASS"),
               "pass_san": sum(1 for i in need if res["san"]["hands"].get(i, [("", "")])[0][0] == "PASS"),
               "test_exec_plain": res["plain"]["tail"], "test_exec_san": res["san"]["tail"],
               "warnings": {k: len(v) for k, v in warns.items()}, "retired_hands_ids": retired,
               "problems": problems, "sec": round(time.time() - t0, 1)}
    with open(os.path.join(OUT, "summary.json"), "w") as f:
        json.dump(summary, f, indent=1)
    for r in rows:
        print(f"{r['state']:5} {r['id']:4} {r['port_checks'][:150]}")
    print(f"ids named by T9: {len(want)}; defined by the hands: {len(need)}; not in the hands' file: {absent or 'none'}")
    print(f"PASS plain {summary['pass_plain']}/{len(need)}, sanitizer {summary['pass_san']}/{len(need)}; "
          f"{' '.join(res['plain']['tail'][:1])} (plain) / {' '.join(res['san']['tail'][:1])} (sanitizer); "
          f"warnings {summary['warnings']}")
    for p in problems:
        print("PROBLEM", p)
    print(f"test_hands_port: {'all ported tests pass' if not problems else str(len(problems)) + ' problems'}, {summary['sec']} s "
          f"-> check/out/test_hands_port/summary.json")
    return 0 if not problems else 1


if __name__ == "__main__":
    sys.exit(main())
